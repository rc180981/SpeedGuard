# Special status per image markers (yellow highlight = Proses, red highlight = Kecepatan >= 40)
# WICAK, KHARIS ANSORI, FADILA HILMA are yellow in image
yellow_names = {'WICAK', 'KHARIS ANSORI', 'FADILA HILMA'}

items = []
lines = [l.strip() for l in raw_data.strip().split('\n') if l.strip()]

for idx, line in enumerate(lines, 1):
    parts = line.split('\t')
    if len(parts) >= 9:
        d_str = parts[1].strip()
        d_m = re.match(r'(\d{2})-([A-Za-z]{3})-(\d{2})', d_str)
        if d_m:
            day, mon, yr = d_m.groups()
            iso_date = f'20{yr}-{month_map.get(mon, "01")}-{day}'
        else:
            iso_date = d_str

        name = parts[2].strip()
        area = parts[3].strip()
        if area == 'e':
            area = 'Area sisi selatan wh3'

        speed_raw = parts[4].strip()
        speed_m = re.search(r'\d+', speed_raw)
        speed = int(speed_m.group(0)) if speed_m else 0

        dept = parts[5].strip()
        nik = parts[6].strip().replace("'", '')
        plat = parts[7].strip().upper()
        veh = parts[8].strip().upper()

        status = 'Proses' if name.upper() in yellow_names else 'Baru'
        remark = ''
        if name.upper() == 'WICAK':
            remark = 'Pelanggaran berulang'
        elif speed >= 45:
            remark = 'Kecepatan sangat tinggi'

        items.append({
            'id': idx,
            'date': iso_date,
            'name': name,
            'area': area,
            'speed': speed,
            'dept': dept,
            'nik': nik,
            'plat': plat,
            'vehicle': veh,
            'status': status,
            'remark': remark
        })

print(f"Total processed: {len(items)}")

# Generate JS code representation
js_lines = ["const INITIAL = ["]
for item in items:
    js_lines.append(f"  {json.dumps(item)},")
js_lines.append("];")
js_code = "\n".join(js_lines)

